// ─── Context ─────────────────────────────────────────────────────────────────
/** Valores a interpolar en el texto: t("clave", { nombre: "Ana" }) reemplaza
 *  cada {nombre} del texto por "Ana". */
type ParamsTexto = Record<string, string | number>;

function interpolar(texto: string, params?: ParamsTexto): string {
  if (!params) return texto;
  let s = texto;
  for (const [k, v] of Object.entries(params)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

interface I18nContextValue {
  idioma: Idioma;
  setIdioma: (i: Idioma) => void;
  t: (clave: ClaveTexto, params?: ParamsTexto) => string;
}

